"""
fish.provenance — from a FISH session back to the code that ran.
Generated by Claude Fable 5 (Anthropic).

Four layers, each narrowing the previous one (see notes/design_abstraction_axes.txt
discussion 2026-08-22 and docs/provenance.md):

  1. runtime  → binaries   snapshot/maps_libs_{stable,shutdown}.json
                           (per ROS process: exe + every mapped .so)
  2. binaries → packages   install layout + ament resource index
                           (rclcpp_components class;lib, pluginlib xml,
                           ament_cmake_export_libraries, lib<pkg> heuristics)
  3. symbols  → sources    ros2:rclcpp_callback_register symbols from the trace
                           (FIRED ones = callback_start seen) resolved against a
                           universal-ctags index of the sources the image was
                           built from ($PROV/tags, $PROV/src)
  4. sources  → includes   per translation unit, `<cc> -E -H` with the flags of
                           $PROV/build/<pkg>/compile_commands.json (configure-only)

Usage (inside a fishwait6-class container, or anywhere $PROV is mounted):
    python3 -m fish.provenance <session_dir> [--prov /opt/fish_provenance]
                               [--install /opt/autoware] [--ros /opt/ros/humble]
                               [--no-includes] [--max-tus N]
Outputs <session_dir>/provenance/{packages.json,symbols.json,includes.json,report.md}
"""
from __future__ import annotations
import os, sys, re, json, glob, shlex, subprocess, collections, time, argparse

# ---------------------------------------------------------------- layer 1

def load_maps(session_dir: str) -> dict:
    """Merge maps_libs_stable + maps_libs_shutdown (union of libs per pid)."""
    procs: dict[int, dict] = {}
    for tag in ("stable", "shutdown"):
        p = os.path.join(session_dir, "snapshot", f"maps_libs_{tag}.json")
        if not os.path.exists(p):
            continue
        d = json.load(open(p))
        for pr in d.get("processes", []):
            cur = procs.setdefault(pr["pid"], {"pid": pr["pid"], "comm": pr.get("comm"), "exe": pr.get("exe"),
                                                "cmdline": pr.get("cmdline"), "libs": set(), "seen": []})
            cur["libs"].update(pr.get("libs", []))
            cur["seen"].append(tag)
            if not cur.get("exe") and pr.get("exe"):
                cur["exe"] = pr["exe"]
    for pr in procs.values():
        pr["libs"] = sorted(pr["libs"])
    return procs

# ---------------------------------------------------------------- layer 2

class PackageResolver:
    """Map an executable / shared object path to the ROS package that ships it."""
    def __init__(self, roots: list[str]):
        self.roots = [os.path.normpath(r) for r in roots if os.path.isdir(r)]
        self.lib2pkg: dict[str, str] = {}
        self.class2lib: dict[str, tuple[str, str]] = {}   # plugin class → (pkg, lib path)
        self.pkgs: set[str] = set()
        for root in self.roots:
            share = os.path.join(root, "share")
            for pkg_dir in glob.glob(os.path.join(share, "*")):
                if os.path.isfile(os.path.join(pkg_dir, "package.xml")):
                    self.pkgs.add(os.path.basename(pkg_dir))
            # rclcpp_components: "class;lib/libX.so"
            for f in glob.glob(os.path.join(share, "ament_index", "resource_index", "rclcpp_components", "*")):
                pkg = os.path.basename(f)
                for line in open(f, errors="replace"):
                    if ";" in line:
                        cls, lib = line.strip().split(";", 1)
                        lp = os.path.normpath(os.path.join(root, lib))
                        self.lib2pkg[lp] = pkg; self.class2lib[cls] = (pkg, lp)
            # pluginlib xml: <library path="..."> (path relative to package prefix, sometimes without lib/)
            for f in glob.glob(os.path.join(share, "ament_index", "resource_index", "*__pluginlib__plugin", "*")):
                pkg = os.path.basename(f)
                for line in open(f, errors="replace"):
                    xml = os.path.join(root, line.strip())
                    if not os.path.isfile(xml):
                        continue
                    for m in re.finditer(r'<library\s+path="([^"]+)"', open(xml, errors="replace").read()):
                        lp = m.group(1)
                        cands = [lp, lp + ".so", os.path.join("lib", lp + ".so"), os.path.join("lib", "lib" + os.path.basename(lp) + ".so")]
                        for c in cands:
                            full = os.path.normpath(os.path.join(root, c))
                            if os.path.exists(full):
                                self.lib2pkg[full] = pkg; break
            # ament_cmake_export_libraries
            for f in glob.glob(os.path.join(share, "*", "cmake", "ament_cmake_export_libraries-extras.cmake")):
                pkg = f.split(os.sep)[-3]
                m = re.search(r'set\(_exported_library_names\s+"([^"]*)"', open(f, errors="replace").read())
                if not m:
                    continue
                for name in m.group(1).split(";"):
                    name = name.strip()
                    if not name or name.startswith("$"):
                        continue
                    for c in (os.path.join(root, "lib", f"lib{name}.so"), os.path.join(root, "lib", name), name):
                        if os.path.isabs(c) and os.path.exists(c):
                            self.lib2pkg[os.path.normpath(c)] = pkg; break
        self._by_len = sorted(self.pkgs, key=len, reverse=True)

    def resolve(self, path: str) -> tuple[str, str]:
        """→ (package, how). how ∈ index | exe_dir | heuristic | system"""
        if not path:
            return ("?", "none")
        p = os.path.normpath(path)
        if p in self.lib2pkg:
            return (self.lib2pkg[p], "index")
        for root in self.roots:
            m = re.match(re.escape(root) + r"/lib/([^/]+)/", p)
            if m and m.group(1) in self.pkgs:
                return (m.group(1), "exe_dir")
        base = os.path.basename(p)
        if any(p.startswith(r + "/") for r in self.roots):
            stem = re.sub(r"\.so(\.[0-9.]+)?$", "", base)
            stem = stem[3:] if stem.startswith("lib") else stem
            for pkg in self._by_len:
                if stem == pkg or stem.startswith(pkg + "_") or stem.startswith(pkg):
                    return (pkg, "heuristic")
            return ("(unresolved:" + base + ")", "unresolved")
        return ("system", "system")

# ---------------------------------------------------------------- layer 3

_EV_RE = re.compile(r"(ros2:(?:rclcpp_callback_register|fish_rclpy_callback_register|callback_start)):.*?vpid = (\d+).*?callback = (0x[0-9A-Fa-f]+)(?:.*?symbol = \"(.*)\" \})?")

def extract_symbols(session_dir: str) -> tuple[dict, set]:
    """babeltrace2 the CTF trace: registered {(vpid, cb): symbol}, fired {(vpid, cb)}."""
    trace = os.path.join(session_dir, "ros2")
    registered: dict[tuple[int, str], str] = {}
    fired: set[tuple[int, str]] = set()
    if not os.path.isdir(trace):
        return registered, fired
    cmd = f"babeltrace2 {shlex.quote(trace)} 2>/dev/null | grep -E 'callback_register|callback_start'"
    with subprocess.Popen(cmd, shell=True, stdout=subprocess.PIPE, text=True, errors="replace") as p:
        for line in p.stdout:
            m = _EV_RE.search(line)
            if not m:
                continue
            ev, vpid, cb, sym = m.group(1), int(m.group(2)), m.group(3).upper(), m.group(4)
            if ev.endswith("callback_start"):
                fired.add((vpid, cb))
            elif sym is not None:
                registered[(vpid, cb)] = sym.replace('\\"', '"')
    return registered, fired


def _strip_templates(s: str) -> str:
    out, depth = [], 0
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth = max(0, depth - 1)
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def _strip_args(s: str) -> str:
    """qualified name before the top-level '(' of the parameter list."""
    depth = 0
    for i, ch in enumerate(s):
        if ch == "(" and depth == 0:
            return s[:i]
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
    return s


def parse_symbol(sym: str) -> dict:
    """→ {'kind': function|class|lambda_in|python|unknown, 'qual': 'ns::Class::method' | 'ns::Class'}"""
    s = sym.strip()
    if "::{lambda" in s:
        head = s.split("::{lambda", 1)[0]
        return {"kind": "lambda_in", "qual": _strip_args(_strip_templates(head)).strip()}
    if s.startswith("std::function<"):
        # type-erased std::function: the symbol is the callback TYPE, the
        # target is unknown at the ROS layer (rclcpp's get_symbol on a
        # std::function) → cannot be resolved without DWARF/uprobes
        return {"kind": "opaque", "qual": _strip_templates(s).strip()}
    if s.startswith("std::_Bind<"):
        m = re.search(r"\(([A-Za-z_][\w:<>, ]*?)::\*", s)
        if m:
            return {"kind": "class", "qual": _strip_templates(m.group(1)).strip()}
        return {"kind": "unknown", "qual": s[:80]}
    if re.match(r"^[A-Za-z_][\w.]*\.[A-Za-z_][\w.]*$", s) and "::" not in s:
        return {"kind": "python", "qual": s}
    q = _strip_args(_strip_templates(s)).strip()
    q = re.sub(r"^(const\s+)?[\w:]+\s+(?=[\w:]+$)", "", q)   # drop return type if any
    if "::" in q:
        return {"kind": "function", "qual": q}
    return {"kind": "unknown", "qual": q}


class TagIndex:
    """universal-ctags file with --extras=+q: qualified name → [(file, line, kind)]."""
    def __init__(self, tags_path: str, src_root: str):
        self.by_qual: dict[str, list] = collections.defaultdict(list)
        self.by_tail: dict[str, list] = collections.defaultdict(list)
        self.src_root = src_root
        if not os.path.exists(tags_path):
            return
        for line in open(tags_path, errors="replace"):
            if line.startswith("!"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            name, fpath = parts[0], parts[1]
            kind, lineno = "", None
            for ext in parts[3:]:
                if ext.startswith("line:"):
                    lineno = int(ext[5:])
                elif ext.startswith("kind:"):
                    kind = ext[5:]
                elif len(ext) == 1 and not kind:
                    kind = ext
            if "::" in name:
                self.by_qual[name].append((fpath, lineno, kind))
                self.by_tail["::".join(name.split("::")[-2:])].append((name, fpath, lineno, kind))

    def resolve(self, qual: str) -> list:
        if qual in self.by_qual:
            return [("exact", *r) for r in self.by_qual[qual]]
        tail = "::".join(qual.split("::")[-2:])
        hits = self.by_tail.get(tail, [])
        return [("tail", f, l, k) for (_n, f, l, k) in hits][:5]

# ---------------------------------------------------------------- layer 4

class CompileDB:
    def __init__(self, prov_root: str):
        self.entries: dict[str, dict] = {}
        for f in glob.glob(os.path.join(prov_root, "build", "*", "compile_commands.json")):
            pkg = f.split(os.sep)[-2]
            try:
                for e in json.load(open(f)):
                    fp = e.get("file", "")
                    if not os.path.isabs(fp):
                        fp = os.path.normpath(os.path.join(e.get("directory", ""), fp))
                    e["_pkg"] = pkg
                    self.entries[os.path.normpath(fp)] = e
            except Exception:
                pass

    def find(self, path: str):
        p = os.path.normpath(path)
        if p in self.entries:
            return self.entries[p]
        base = os.path.basename(p)
        cands = [e for fp, e in self.entries.items() if fp.endswith("/" + base)]
        return cands[0] if len(cands) == 1 else None

    def tus_including(self, header_basename: str, limit: int = 3):
        """cheap fallback for headers: TUs in the same package tree whose name matches."""
        stem = re.sub(r"\.(hpp|h)$", "", header_basename)
        return [e for fp, e in self.entries.items() if os.path.basename(fp).startswith(stem + ".")][:limit]


def include_graph(entry: dict, timeout: int = 90) -> dict:
    cmd = entry.get("arguments") or shlex.split(entry.get("command", ""))
    if not cmd:
        return {"error": "no command"}
    args = []
    skip = False
    for i, a in enumerate(cmd):
        if skip:
            skip = False; continue
        if a in ("-o",):
            skip = True; continue
        if a == "-c":
            continue
        args.append(a)
    args += ["-E", "-H", "-o", "/dev/null"]
    try:
        p = subprocess.run(args, cwd=entry.get("directory"), capture_output=True, text=True, timeout=timeout, errors="replace")
    except subprocess.TimeoutExpired:
        return {"error": "timeout"}
    except FileNotFoundError as e:
        return {"error": f"compiler not found: {e}"}
    incs, maxd = [], 0
    for line in p.stderr.splitlines():
        m = re.match(r"^(\.+) (.+)$", line)
        if m:
            d = len(m.group(1)); incs.append((d, m.group(2))); maxd = max(maxd, d)
    return {"rc": p.returncode, "n_includes": len(incs), "max_depth": maxd,
            "direct": [pth for d, pth in incs if d == 1],
            "all": [pth for _d, pth in incs],
            "stderr_tail": "" if p.returncode == 0 else p.stderr[-600:]}

# ---------------------------------------------------------------- main

def run(session_dir: str, prov: str, install: str, ros: str, do_includes: bool, max_tus: int) -> str:
    t0 = time.time()
    out_dir = os.path.join(session_dir, "provenance"); os.makedirs(out_dir, exist_ok=True)
    log = lambda *a: print("[provenance]", *a, flush=True)

    # layer 1 + 2
    procs = load_maps(session_dir)
    resolver = PackageResolver([install, ros])
    pkg_use = collections.defaultdict(lambda: {"pids": set(), "libs": set(), "exes": set()})
    for pid, pr in procs.items():
        exe_pkg, how = resolver.resolve(pr.get("exe") or "")
        pr["exe_pkg"] = exe_pkg
        if exe_pkg not in ("system", "?"):
            pkg_use[exe_pkg]["pids"].add(pid); pkg_use[exe_pkg]["exes"].add(pr.get("exe"))
        pr["lib_pkgs"] = {}
        for lib in pr["libs"]:
            pkg, how = resolver.resolve(lib)
            pr["lib_pkgs"][lib] = pkg
            if pkg not in ("system",) and not pkg.startswith("(unresolved"):
                pkg_use[pkg]["pids"].add(pid); pkg_use[pkg]["libs"].add(lib)
    n_sys = sum(1 for pr in procs.values() for l, p in pr["lib_pkgs"].items() if p == "system")
    n_unres = sum(1 for pr in procs.values() for l, p in pr["lib_pkgs"].items() if p.startswith("(unresolved"))
    log(f"layer 1/2: {len(procs)} ROS processes, {len(pkg_use)} packages mapped "
        f"({n_sys} system lib mappings, {n_unres} unresolved), {len(resolver.pkgs)} packages installed")
    packages = {pkg: {"pids": sorted(v["pids"]), "libs": sorted(v["libs"]), "exes": sorted(x for x in v["exes"] if x)}
                for pkg, v in pkg_use.items()}
    json.dump({"processes": procs, "packages": packages, "n_installed": len(resolver.pkgs),
               "unused_installed": sorted(resolver.pkgs - set(packages))},
              open(os.path.join(out_dir, "packages.json"), "w"), indent=1, default=str)

    # layer 3
    registered, fired = extract_symbols(session_dir)
    log(f"layer 3: {len(registered)} registered callbacks, {len(fired & set(registered))} fired")
    tags = TagIndex(os.path.join(prov, "tags"), os.path.join(prov, "src"))
    symbols = []
    files_fired: dict[str, dict] = {}
    resolved = 0
    for (vpid, cb), sym in registered.items():
        info = parse_symbol(sym)
        hits = tags.resolve(info["qual"]) if info["kind"] != "python" and tags.by_qual else []
        is_fired = (vpid, cb) in fired
        pr = procs.get(vpid, {})
        rec = {"vpid": vpid, "cb": cb, "symbol": sym, "kind": info["kind"], "qual": info["qual"],
               "fired": is_fired, "exe_pkg": pr.get("exe_pkg"),
               "hits": [{"match": h[0], "file": h[1], "line": h[2], "tag_kind": h[3]} for h in hits]}
        symbols.append(rec)
        if hits:
            resolved += 1
            if is_fired:
                f = hits[0][1]
                d = files_fired.setdefault(f, {"symbols": set(), "pkg": None})
                d["symbols"].add(info["qual"])
    log(f"layer 3: {resolved}/{len(registered)} symbols resolved to source; "
        f"{len(files_fired)} distinct source files behind the FIRED callbacks")
    json.dump({"symbols": symbols, "n_registered": len(registered), "n_fired": len(fired & set(registered)),
               "n_resolved": resolved, "tags_available": bool(tags.by_qual)},
              open(os.path.join(out_dir, "symbols.json"), "w"), indent=1)

    # layer 4
    includes = {}
    if do_includes:
        cdb = CompileDB(prov)
        log(f"layer 4: compile database with {len(cdb.entries)} translation units")
        done = 0
        for f, d in sorted(files_fired.items()):
            if done >= max_tus:
                break
            fabs = f if os.path.isabs(f) else os.path.normpath(os.path.join(prov, f))
            entry = cdb.find(fabs)
            tus = [entry] if entry else cdb.tus_including(os.path.basename(fabs))
            if not tus:
                includes[f] = {"error": "no compile entry (header without matching TU, or package not configured)"}
                continue
            e = tus[0]
            g = include_graph(e)
            g["tu"] = e.get("file"); g["pkg"] = e.get("_pkg"); g["symbols"] = sorted(d["symbols"])
            includes[f] = g; done += 1
            if "n_includes" in g:
                log(f"   {os.path.basename(f)} ({e.get('_pkg')}): {g['n_includes']} includes, depth {g['max_depth']}")
        json.dump(includes, open(os.path.join(out_dir, "includes.json"), "w"), indent=1)

    # report
    lines = [f"# Provenance report — {os.path.basename(session_dir.rstrip('/'))}", "",
             f"Generated by fish.provenance in {time.time()-t0:.0f} s.", "",
             "## Layer 1 → 2: runtime → binaries → packages", "",
             f"- ROS processes observed (maps snapshot): **{len(procs)}**",
             f"- packages touched (exe or mapped lib): **{len(packages)}** of {len(resolver.pkgs)} installed",
             f"- installed but never mapped: {len(resolver.pkgs - set(packages))}",
             f"- system (non-ROS) library mappings: {n_sys}; unresolved ROS-root libs: {n_unres}", "",
             "| package | processes | libs | exes |", "|---|---|---|---|"]
    for pkg, v in sorted(packages.items(), key=lambda kv: -len(kv[1]["pids"]))[:60]:
        lines.append(f"| {pkg} | {len(v['pids'])} | {len(v['libs'])} | {len(v['exes'])} |")
    lines += ["", "## Layer 3: symbols → sources", "",
              f"- registered callback symbols: **{len(registered)}**, fired: **{len(fired & set(registered))}**",
              f"- resolved to source (ctags): **{resolved}** — tags index {'present' if tags.by_qual else 'MISSING'}",
              f"- distinct source files behind fired callbacks: **{len(files_fired)}**", ""]
    kinds = collections.Counter(s["kind"] for s in symbols)
    lines.append("symbol kinds: " + ", ".join(f"{k}={v}" for k, v in kinds.most_common()))
    lines += ["", "| source file | fired symbols |", "|---|---|"]
    for f, d in sorted(files_fired.items(), key=lambda kv: -len(kv[1]["symbols"]))[:80]:
        lines.append(f"| {f} | {len(d['symbols'])} |")
    if do_includes:
        ok = [g for g in includes.values() if "n_includes" in g]
        lines += ["", "## Layer 4: translation units → includes", "",
                  f"- TUs analysed: **{len(ok)}** (of {len(files_fired)} files; --max-tus {max_tus}); failures: {len(includes)-len(ok)}",
                  f"- total distinct headers pulled in: **{len({h for g in ok for h in g.get('all', [])})}**", "",
                  "| TU | package | direct includes | total | max depth |", "|---|---|---|---|---|"]
        for f, g in sorted(includes.items(), key=lambda kv: -(kv[1].get("n_includes") or 0))[:60]:
            if "n_includes" in g:
                lines.append(f"| {os.path.basename(f)} | {g.get('pkg')} | {len(g['direct'])} | {g['n_includes']} | {g['max_depth']} |")
    open(os.path.join(out_dir, "report.md"), "w").write("\n".join(lines) + "\n")
    log(f"done → {out_dir}/report.md")
    return out_dir


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("session_dir")
    ap.add_argument("--prov", default=os.environ.get("FISH_PROV", "/opt/fish_provenance"))
    ap.add_argument("--install", default="/opt/autoware")
    ap.add_argument("--ros", default="/opt/ros/humble")
    ap.add_argument("--no-includes", action="store_true")
    ap.add_argument("--max-tus", type=int, default=400)
    a = ap.parse_args(argv)
    run(a.session_dir, a.prov, a.install, a.ros, not a.no_includes, a.max_tus)
    return 0


if __name__ == "__main__":
    sys.exit(main())
